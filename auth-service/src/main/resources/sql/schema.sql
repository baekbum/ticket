DROP TABLE IF EXISTS user_login_locks;
DROP TABLE IF EXISTS processed_user_events;
DROP TABLE IF EXISTS auth CASCADE;

CREATE TABLE auth (
    id BIGINT PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'ROLE_USER',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    is_blacklisted BOOLEAN NOT NULL DEFAULT FALSE,
    token_version BIGINT NOT NULL DEFAULT 1 CHECK (token_version >= 1),
    blacklisted_until DATE
);

CREATE INDEX idx_auth_user_id ON auth(user_id);

-- DB 적용 이력을 회원 변경과 함께 커밋한다. 계정 삭제 후에도 멱등키를 보존한다.
CREATE TABLE processed_user_events (
    processed_user_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(100) NOT NULL,
    auth_id BIGINT NOT NULL,
    user_id VARCHAR(50) NOT NULL,
    event_type VARCHAR(20) NOT NULL CHECK (event_type IN ('CREATE', 'UPDATE')),
    request_hash VARCHAR(64) NOT NULL,
    processed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_processed_user_events_auth_key UNIQUE (auth_id, idempotency_key)
);
CREATE INDEX idx_processed_user_events_user ON processed_user_events(user_id);

-- 계정별 연속 로그인 실패와 비밀번호 재설정 전까지 유지되는 잠금을 관리한다.
CREATE TABLE user_login_locks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_id BIGINT NOT NULL UNIQUE REFERENCES auth(id) ON DELETE CASCADE,
    failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
    last_failed_at TIMESTAMP,
    locked_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_login_lock_state CHECK (
        (failed_attempts < 5 AND locked_at IS NULL)
        OR (failed_attempts = 5 AND locked_at IS NOT NULL)
    )
);
